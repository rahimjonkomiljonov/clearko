"""Run the full pipeline on the eval documents and compare it with a plain baseline.

    cd backend && .venv/Scripts/python ../eval/run_pipeline.py [--only NAME ...] [--lang en]

For every document it saves a review sheet for a Korean speaker:
    eval/results/review/<doc>.md       synthetic / public documents (safe to commit)
    eval/results/raw/review/<doc>.md   private documents (git-ignored)
and a summary table in eval/results/pipeline.md.

Baseline = what you get by pasting the OCR text into the same local model with one
"explain this and point out risks" prompt: no clause-by-clause review, no rules, no quote checks.
(To compare with a hosted chatbot, paste eval/results/chatbot_prompt.txt into it by hand.)
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "backend"))
sys.path.insert(0, str(ROOT))

from planted import PLANTED, found, recall

from app.config import get_settings
from app.explain import LLMError, get_llm_client
from app.explain.llm_client import OllamaClient
from app.ocr import get_engine
from app.pipeline import analyze, load_pages

DATA = ROOT / "data"
RESULTS = ROOT / "results"


@dataclass
class Doc:
    name: str
    paths: list[Path]
    kind: str  # what it is, for the table
    private: bool = False
    planted: str | None = None  # key into PLANTED
    blank: bool = False  # a blank form: the right answer is a warning and no red flags


def documents() -> list[Doc]:
    syn, priv, pub = DATA / "synthetic", DATA / "private", DATA / "public"
    return [
        Doc("parttime_photo", [syn / "parttime_contract_photo.jpg"], "part-time contract (synthetic photo)",
            planted="parttime"),
        Doc("student_photo", [syn / "student_confirmation_photo.jpg"], "student work form (synthetic photo)",
            planted="student"),
        Doc("parttime_pdf", [syn / "parttime_contract.pdf"], "part-time contract (synthetic PDF)",
            planted="parttime"),
        Doc("student_pdf", [syn / "student_confirmation.pdf"], "student work form (synthetic PDF)",
            planted="student"),
        Doc("seoul_blank", [pub / "seoul_monthly_rent_a.pdf"], "blank Seoul lease form (public)", blank=True),
        Doc("moj_blank", [pub / "moj_standard_lease.pdf"], "blank MOJ standard lease (public)", blank=True),
        Doc("rental_real", [priv / "rental_01" / "redacted"], "real rental contract, redacted", private=True),
        Doc("phone_real", [priv / "phone_01"], "real phone plan flyers (English)", private=True),
    ]


BASELINE_SYSTEM = "You are a helpful assistant."
BASELINE_PROMPT = (
    "Here is the text of a Korean document, read by OCR. I am a foreign student in Korea.\n"
    "Explain what it says in plain English and point out anything risky for me.\n\n{text}"
)


def baseline(llm, text: str) -> str | None:
    """None if the model server fails twice (seen once: HTTP 500 while the GPU is shared)."""
    for attempt in range(2):
        try:
            return llm.generate(BASELINE_SYSTEM, [("user", BASELINE_PROMPT.format(text=text))])
        except LLMError as e:
            print(f"baseline attempt {attempt + 1} failed: {e}", flush=True)
            time.sleep(5)
    return None


def review_sheet(doc: Doc, result, ocr_text: str, base: str | None, secs: float) -> str:
    o = [f"# Review sheet: {doc.name}", f"*{doc.kind}*. Generated by ClearKo in {secs:.0f} s.\n"]
    o.append("Reviewer: tick what is right, cross what is wrong, write corrections under the item.\n")
    o.append(f"**Detected type:** {result.doc_type.value}  |  **OCR confidence:** "
             f"{result.ocr_confidence:.2f}" if result.ocr_confidence else f"**Detected type:** {result.doc_type.value}")
    o.append("\n## 1. OCR text (is the Korean read correctly? mark mistakes)\n")
    o.append("```\n" + ocr_text + "\n```\n")
    o.append(f"## 2. Summary\n\n{result.summary}\n\n- [ ] accurate  - [ ] misleading  - [ ] wrong\n")
    o.append("## 3. Red flags\n")
    for i, f in enumerate(result.red_flags, 1):
        o.append(f"### {i}. [{f.severity.value.upper()}] {f.title}\n")
        o.append(f"{f.explanation}\n")
        if f.original_text:
            o.append(f"> Korean: {f.original_text}  (quote matched to scan: {'yes' if f.quote_verified else 'no'})\n")
        o.append("- [ ] real problem  - [ ] not a problem (false alarm)  - [ ] explanation correct  "
                 "- [ ] severity right\n")
    if not result.red_flags:
        o.append("(none)\n")
    o.append("## 4. Key facts\n")
    for k in result.key_facts:
        o.append(f"- **{k.label}:** {k.value}   - [ ] correct")
    o.append("\n## 5. To-do list\n")
    for t in result.todos:
        o.append(f"- {t.action}" + (f" (by {t.deadline})" if t.deadline else "") + "   - [ ] sensible")
    if result.warnings:
        o.append("\n## 6. Warnings shown to the user\n")
        o += [f"- {w}" for w in result.warnings]
    if base is not None:
        o.append("\n## Baseline answer (same model, one plain prompt, for comparison)\n")
        o.append(base + "\n")
    o.append("\n## Problems missed? (reviewer: list anything important the sheet did not mention)\n\n- \n")
    return "\n".join(o)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", help="document names to run")
    ap.add_argument("--lang", default="en")
    ap.add_argument("--no-baseline", action="store_true")
    args = ap.parse_args()

    cfg = get_settings()
    llm = get_llm_client(cfg.llm_provider, cfg.llm_api_key, cfg.llm_model, cfg.llm_base_url)
    engine = get_engine(cfg.ocr_engine, cfg.ocr_device)
    # the baseline answers in free text; ClearKo's own calls keep the JSON-constrained client
    plain = OllamaClient(cfg.llm_model, cfg.llm_base_url or "http://localhost:11434", force_json=False)
    (RESULTS / "review").mkdir(parents=True, exist_ok=True)
    (RESULTS / "raw" / "review").mkdir(parents=True, exist_ok=True)

    rows = []
    for doc in documents():
        if args.only and doc.name not in args.only:
            continue
        if not all(p.exists() for p in doc.paths):
            print(f"skip {doc.name}: files missing")
            continue
        t0 = time.perf_counter()
        pages = load_pages(doc.paths)
        result, reading = analyze(pages, args.lang, engine, llm, max_side=cfg.max_image_side,
                                  blur_threshold=cfg.blur_threshold)
        secs = time.perf_counter() - t0
        base = None if args.no_baseline else baseline(plain, reading.text)

        flag_text = "\n".join(f"{f.title} {f.explanation} {f.original_text or ''}" for f in result.red_flags)
        row = {
            "doc": doc.name, "kind": doc.kind, "seconds": round(secs), "flags": len(result.red_flags),
            "high": sum(f.severity.value == "high" for f in result.red_flags),
            "blank_warned": any("blank" in w.lower() or "empty" in w.lower() for w in result.warnings),
            "unverified_quotes": sum(bool(f.original_text) and not f.quote_verified for f in result.red_flags),
            "baseline_chars": len(base) if base else None,
        }
        if doc.planted:
            row["planted_total"] = len(PLANTED[doc.planted])
            row["clearko_found"] = sum(found(doc.planted, flag_text).values())
            row["clearko_missed"] = [k for k, v in found(doc.planted, flag_text).items() if not v]
            if base:
                row["baseline_found"] = sum(found(doc.planted, base).values())
                row["baseline_missed"] = [k for k, v in found(doc.planted, base).items() if not v]
                row["baseline_recall"] = recall(doc.planted, base)
        rows.append(row)
        sheet = review_sheet(doc, result, reading.text, base, secs)
        out = (RESULTS / "raw" / "review" if doc.private else RESULTS / "review") / f"{doc.name}.md"
        out.write_text(sheet, encoding="utf-8")
        print(json.dumps(row, ensure_ascii=False), flush=True)

    prev_file = RESULTS / "raw" / "pipeline.json"
    if args.only and prev_file.exists():  # a partial run updates its rows and keeps the others
        names = {r["doc"] for r in rows}
        keep = [r for r in json.loads(prev_file.read_text(encoding="utf-8")) if r["doc"] not in names]
        order = [d.name for d in documents()]
        rows = sorted(keep + rows, key=lambda r: order.index(r["doc"]))
    (RESULTS / "raw" / "pipeline.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False), encoding="utf-8")
    (RESULTS / "pipeline.md").write_text(report(rows), encoding="utf-8")
    print("wrote", RESULTS / "pipeline.md")


def report(rows: list[dict]) -> str:
    o = ["# Pipeline results\n",
         "Same local model (`qwen2.5:7b`) for both columns. *Baseline* = one plain prompt with the OCR text;",
         "*ClearKo* = clause-by-clause review + rules + quote and number checks.\n",
         "## Planted problems found (synthetic documents)\n",
         "| Document | Planted | ClearKo found | Baseline found | ClearKo missed | Baseline missed |",
         "|---|---|---|---|---|---|"]
    for r in rows:
        if "planted_total" in r:
            o.append(f"| {r['doc']} | {r['planted_total']} | **{r['clearko_found']}** | "
                     f"{r.get('baseline_found', 'n/a')} | {', '.join(r['clearko_missed']) or '-'} | "
                     f"{', '.join(r.get('baseline_missed', [])) or '-'} |")
    o += ["\n## Blank forms (the right answer is a warning and no red flags)\n",
          "| Document | Red flags | Warned it is blank |", "|---|---|---|"]
    for r in rows:
        if r["doc"].endswith("_blank"):
            o.append(f"| {r['doc']} | {r['flags']} | {'yes' if r['blank_warned'] else 'no'} |")
    o += ["\n## All runs\n", "| Document | Time | Red flags | High | Quotes not matched to scan |", "|---|---|---|---|---|"]
    for r in rows:
        o.append(f"| {r['doc']} | {r['seconds']} s | {r['flags']} | {r['high']} | {r['unverified_quotes']} |")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    main()
